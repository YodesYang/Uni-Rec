"""Generate ns_groups.json variants that re-order fids by vocab tier.

Rationale (T29 / ADR-009):
    The RankMixerNSTokenizer concatenates fid embeddings in the order given
    by ns_groups and then chunks the flat tensor into num_ns_tokens equal
    slices, each fed to an independent Linear projection. The order of fids
    therefore directly controls "which fids share a chunk projection".
    With --ns_groups_json "" (current SOTA config) the fallback is singleton
    groups in fid-index order, which is effectively random because fids are
    anonymized. DECEM (Industrial Track Rank 1) explicitly said the
    Tokenization fix was a small but high-ROI change.

    This script produces two alternative orderings:

    - ``vocab_tier``: group fids into small/mid/large vocab tiers, and
      within each tier sort by vocab descending. Each tier gets one JSON
      group. The RankMixer tokenizer still produces num_ns_tokens chunks
      (unchanged by groups), but within each chunk fids have similar
      embedding-sparsity characteristics (small vocab → saturates quickly,
      large vocab → sparse gradient). This is expected to reduce gradient
      interference between "fast-learning" and "slow-learning" fids inside
      the same shared Linear projection.

    - ``vocab_desc``: a simpler ordering — just sort all fids by vocab
      descending in a single group. This puts the highest-cardinality
      (most-informative, most-overfit-prone) fids at the front of the
      concatenation, and the chunk 0 / first few chunks will pick them up.

Usage:
    python3 scripts/gen_ns_groups_vocab_tier.py \\
        --schema data/demo/schema.json \\
        --out src/ns_groups_vocab_tier.json \\
        --mode vocab_tier

Output JSON is consumed by src/train.py via --ns_groups_json.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List, Tuple


def _parse_schema(schema_path: Path) -> Tuple[List[Tuple[int, int, int]], List[Tuple[int, int, int]]]:
    """Return (user_int_entries, item_int_entries) where each entry is (fid, vocab, dim)."""
    with schema_path.open("r", encoding="utf-8") as f:
        schema = json.load(f)
    user_int = [tuple(x) for x in schema["user_int"]]
    item_int = [tuple(x) for x in schema["item_int"]]
    return user_int, item_int


def _vocab_tier_groups(
    entries: List[Tuple[int, int, int]],
    tier_boundaries: Tuple[int, int] = (100, 2000),
) -> Dict[str, List[int]]:
    """Split fids into [small, mid, large] vocab tiers.

    Args:
        entries: [(fid, vocab, dim), ...]
        tier_boundaries: (small_upper, mid_upper). vocab <= small_upper is
            small; small_upper < vocab <= mid_upper is mid; vocab > mid_upper
            is large.
    """
    small_upper, mid_upper = tier_boundaries
    small: List[Tuple[int, int]] = []
    mid: List[Tuple[int, int]] = []
    large: List[Tuple[int, int]] = []
    for fid, vocab, _dim in entries:
        if vocab <= small_upper:
            small.append((fid, vocab))
        elif vocab <= mid_upper:
            mid.append((fid, vocab))
        else:
            large.append((fid, vocab))
    small.sort(key=lambda x: -x[1])
    mid.sort(key=lambda x: -x[1])
    large.sort(key=lambda x: -x[1])
    out: Dict[str, List[int]] = {}
    if large:
        out["T_large"] = [fid for fid, _ in large]
    if mid:
        out["T_mid"] = [fid for fid, _ in mid]
    if small:
        out["T_small"] = [fid for fid, _ in small]
    return out


def _vocab_desc_groups(entries: List[Tuple[int, int, int]]) -> Dict[str, List[int]]:
    ordered = sorted(entries, key=lambda x: -x[1])
    return {"all_desc": [fid for fid, _, _ in ordered]}


def _build_output(user_entries, item_entries, mode: str) -> Dict:
    if mode == "vocab_tier":
        user_groups = _vocab_tier_groups(user_entries)
        item_groups = _vocab_tier_groups(item_entries)
        comment = (
            "T29 variant B: fids grouped by vocab tier "
            "(small<=100, 100<mid<=2000, large>2000); within each tier "
            "sorted by vocab descending. RankMixer chunk projection sees "
            "homogeneous embedding-sparsity within each chunk."
        )
    elif mode == "vocab_desc":
        user_groups = _vocab_desc_groups(user_entries)
        item_groups = _vocab_desc_groups(item_entries)
        comment = (
            "T29 variant C: all fids sorted by vocab descending, single "
            "group. Highest-cardinality fids land at chunk 0."
        )
    else:
        raise ValueError(f"Unknown mode: {mode}")
    return {
        "_purpose": "ns_groups auto-generated by scripts/gen_ns_groups_vocab_tier.py",
        "_mode": mode,
        "_comment": comment,
        "user_ns_groups": user_groups,
        "item_ns_groups": item_groups,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, required=True,
                        help="Path to schema.json (e.g. data/demo/schema.json)")
    parser.add_argument("--out", type=Path, required=True,
                        help="Output path for ns_groups JSON")
    parser.add_argument("--mode", type=str, default="vocab_tier",
                        choices=["vocab_tier", "vocab_desc"])
    parser.add_argument("--small_upper", type=int, default=100,
                        help="upper bound of small-vocab tier (default 100)")
    parser.add_argument("--mid_upper", type=int, default=2000,
                        help="upper bound of mid-vocab tier (default 2000)")
    args = parser.parse_args()

    user_entries, item_entries = _parse_schema(args.schema)
    if args.mode == "vocab_tier":
        # Override tier boundaries if user supplied custom values.
        user_groups = _vocab_tier_groups(
            user_entries, (args.small_upper, args.mid_upper))
        item_groups = _vocab_tier_groups(
            item_entries, (args.small_upper, args.mid_upper))
        out_dict = {
            "_purpose": "ns_groups auto-generated by scripts/gen_ns_groups_vocab_tier.py",
            "_mode": "vocab_tier",
            "_tier_boundaries": [args.small_upper, args.mid_upper],
            "_comment": (
                "T29 variant B: vocab tier grouping; within each tier "
                "sorted by vocab desc. See scripts/gen_ns_groups_vocab_tier.py."
            ),
            "user_ns_groups": user_groups,
            "item_ns_groups": item_groups,
        }
    else:
        out_dict = _build_output(user_entries, item_entries, args.mode)

    # Sanity checks: every fid appears exactly once.
    def _flatten(groups: Dict[str, List[int]]) -> List[int]:
        acc: List[int] = []
        for v in groups.values():
            acc.extend(v)
        return acc

    user_flat = _flatten(out_dict["user_ns_groups"])
    item_flat = _flatten(out_dict["item_ns_groups"])
    user_fids = {fid for fid, _, _ in user_entries}
    item_fids = {fid for fid, _, _ in item_entries}
    assert set(user_flat) == user_fids, (
        f"user_ns_groups missing/extra fids: "
        f"{user_fids ^ set(user_flat)}")
    assert set(item_flat) == item_fids, (
        f"item_ns_groups missing/extra fids: "
        f"{item_fids ^ set(item_flat)}")
    assert len(user_flat) == len(set(user_flat)), "user_ns_groups has duplicates"
    assert len(item_flat) == len(set(item_flat)), "item_ns_groups has duplicates"

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as f:
        json.dump(out_dict, f, indent=2)
    print(f"Wrote {args.out} (mode={args.mode})")
    print(f"  user groups: {[(k, len(v)) for k, v in out_dict['user_ns_groups'].items()]}")
    print(f"  item groups: {[(k, len(v)) for k, v in out_dict['item_ns_groups'].items()]}")


if __name__ == "__main__":
    main()
